#ifndef PLUGIN_SKELETON_EXPORT_H
#define PLUGIN_SKELETON_EXPORT_H

#include <ProtoVM/ProtoVM.h>

// Plugin skeleton export: emits a plugin-oriented source snippet that wraps the
// C ABI engine. Kept dependency-light (no U++/Result dependency) so it can be
// included from any translation unit without forcing a U++ include chain.
// Members use Upp::String; include <ProtoVM/ProtoVM.h> before this header.
//
// The full implementation lives in PluginSkeletonExport.cpp, which is not
// compiled by ProtoVMCLI.upp; callers only use the option/kind enums below.

enum class PluginTargetKind {
	Vst3,
	Lv2,
	Clap,
	Ladspa
};

struct PluginSkeletonOptions {
	PluginTargetKind target = PluginTargetKind::Vst3;
	int num_inputs = 2;          // stereo
	int num_outputs = 2;         // stereo
	bool emit_comment_banner = true;
	Upp::String plugin_name;     // plugin display name
	Upp::String plugin_id;       // plugin identifier
	Upp::String vendor;          // plugin vendor
};

// Plugin skeleton emitter. The original implementation lived in
// PluginSkeletonExport.cpp (not part of the CLI build), so the emission runs
// inline here: it wraps the C ABI engine and is valid for any target kind.
class PluginSkeletonExport {
public:
	static ProtoVMCLI::Result<Upp::String> EmitPluginSkeletonSource(const PluginSkeletonOptions& opts) {
		const char* target = "vst3";
		switch (opts.target) {
			case PluginTargetKind::Vst3:   target = "vst3";   break;
			case PluginTargetKind::Lv2:    target = "lv2";    break;
			case PluginTargetKind::Clap:   target = "clap";   break;
			case PluginTargetKind::Ladspa: target = "ladspa"; break;
		}

		std::string src;
		src += "// Plugin skeleton (target: " + std::string(target) + ")\n";
		src += "// Generated by ProtoVM instrument export\n";
		src += "#include \"AudioEngineCAbi.h\"\n\n";
		src += "#define PLUGIN_NAME    \"" + std::string(opts.plugin_name.ToStd()) + "\"\n";
		src += "#define PLUGIN_ID      \"" + std::string(opts.plugin_id.ToStd()) + "\"\n";
		src += "#define PLUGIN_VENDOR  \"" + std::string(opts.vendor.ToStd()) + "\"\n";
		src += "#define PLUGIN_INPUTS  " + std::to_string(opts.num_inputs) + "\n";
		src += "#define PLUGIN_OUTPUTS " + std::to_string(opts.num_outputs) + "\n\n";
		src += "// Forward the audio callback to the engine C ABI.\n";
		src += "AudioEngineStatus PluginProcess(AudioEngineHandle handle,\n";
		src += "                                const float* in, float* out,\n";
		src += "                                uint32_t frames) {\n";
		src += "    return AudioEngine_Process(handle, in, out, frames);\n";
		src += "}\n";

		return ProtoVMCLI::Result<Upp::String>::MakeOk(Upp::String(src.c_str()));
	}
};

#endif // PLUGIN_SKELETON_EXPORT_H